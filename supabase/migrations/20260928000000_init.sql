-- RPCs
-- ---------------------------------------------------------------------------

-- Create a session with a unique 6-character code (ambiguous 0/O/1/I omitted).
create or replace function public.create_session()
returns table (id uuid, code text, host_key uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  new_code text;
  new_id uuid;
  new_key uuid;
begin
  loop
    new_code := '';
    for i in 1..6 loop
      new_code := new_code || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
    end loop;
    begin
      insert into sessions (code) values (new_code) returning sessions.id into new_id;
      exit;
    exception when unique_violation then
      -- collision: try another code
    end;
  end loop;
  insert into session_host_keys (session_id) values (new_id) returning session_host_keys.host_key into new_key;
  return query select new_id, new_code, new_key;
end;
$$;

create or replace function public.end_session(p_session_id uuid, p_host_key uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from session_host_keys k
                 where k.session_id = p_session_id and k.host_key = p_host_key) then
    raise exception 'Not allowed to end this session' using errcode = '42501';
  end if;
  update sessions set status = 'ended', ended_at = now() where id = p_session_id;
  return true;
end;
$$;

-- Classifier lock (called by the Edge Function with the service role).
create or replace function public.try_acquire_classifier_lock(p_session_id uuid, p_seconds integer default 90)
returns boolean
language sql
security definer
set search_path = public
as $$
  with claimed as (
    update sessions
       set classifier_locked_until = now() + make_interval(secs => p_seconds)
     where id = p_session_id
       and (classifier_locked_until is null or classifier_locked_until < now())
    returning 1
  )
  select exists (select 1 from claimed);
$$;

create or replace function public.extend_classifier_lock(p_session_id uuid, p_seconds integer default 90)
returns void
language sql
security definer
set search_path = public
as $$
  update sessions set classifier_locked_until = now() + make_interval(secs => p_seconds)
   where id = p_session_id;
$$;

create or replace function public.release_classifier_lock(p_session_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  update sessions set classifier_locked_until = null where id = p_session_id;
$$;

revoke execute on function public.try_acquire_classifier_lock(uuid, integer) from public, anon, authenticated;
revoke execute on function public.extend_classifier_lock(uuid, integer)      from public, anon, authenticated;
revoke execute on function public.release_classifier_lock(uuid)              from public, anon, authenticated;
grant execute on function public.try_acquire_classifier_lock(uuid, integer) to service_role;
grant execute on function public.extend_classifier_lock(uuid, integer)      to service_role;
grant execute on function public.release_classifier_lock(uuid)              to service_role;
grant execute on function public.create_session() to anon, authenticated;
grant execute on function public.end_session(uuid, uuid) to anon, authenticated;

