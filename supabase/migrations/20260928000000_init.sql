-- Getit – Questions Box: core schema
-- Sessions -> participants -> questions, plus AI-generated question groups.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table public.sessions (
  id          uuid primary key default gen_random_uuid(),
  code        text not null unique check (code ~ '^[A-Z0-9]{6}$'),
  status      text not null default 'active' check (status in ('active', 'ended')),
  created_at  timestamptz not null default now(),
  ended_at    timestamptz,
  -- Serialises AI classification per session so two concurrent workers never
  -- create duplicate groups for the same concept.
  classifier_locked_until timestamptz
);

-- Secret used by the instructor's browser to manage its session (e.g. end it).
-- Kept in its own table with RLS and no policies so anon can never read it.
create table public.session_host_keys (
  session_id uuid primary key references public.sessions(id) on delete cascade,
  host_key   uuid not null default gen_random_uuid()
);

create table public.participants (
  id            uuid primary key default gen_random_uuid(),
  session_id    uuid not null references public.sessions(id) on delete cascade,
  display_name  text not null check (char_length(btrim(display_name)) between 1 and 60),
  created_at    timestamptz not null default now()
);
create index participants_session_idx on public.participants(session_id);

create table public.question_groups (
  id                       uuid primary key default gen_random_uuid(),
  session_id               uuid not null references public.sessions(id) on delete cascade,
  title                    text not null,
  representative_question  text not null,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now()
);
create index question_groups_session_idx on public.question_groups(session_id);

create table public.questions (
  id                      uuid primary key default gen_random_uuid(),
  session_id              uuid not null references public.sessions(id) on delete cascade,
  participant_id          uuid not null references public.participants(id) on delete cascade,
  text                    text not null check (char_length(btrim(text)) between 1 and 1000),
  created_at              timestamptz not null default now(),
  -- A question belongs to at most one group.
  group_id                uuid references public.question_groups(id) on delete set null,
  classification_status   text not null default 'pending'
                            check (classification_status in ('pending', 'processing', 'classified')),
  classification_attempts integer not null default 0,
  classification_error    text,
  classification_updated_at timestamptz not null default now(),
  -- Idempotency key generated by the submitting browser; a retried submit
  -- after a network blip can never create a second copy of the question.
  client_request_id       uuid unique
);
create index questions_session_idx on public.questions(session_id, created_at desc);
create index questions_pending_idx on public.questions(session_id, created_at)
  where classification_status <> 'classified';
create index questions_group_idx on public.questions(group_id);

-- ---------------------------------------------------------------------------
-- Row level security
-- MVP has no accounts: anyone with the anon key may read session data (needed
-- for Realtime) and may join / ask in *active* sessions. All AI writes happen
-- in the Edge Function with the service role, which bypasses RLS.
-- ---------------------------------------------------------------------------

alter table public.sessions          enable row level security;
alter table public.session_host_keys enable row level security;
alter table public.participants      enable row level security;
alter table public.question_groups   enable row level security;
alter table public.questions         enable row level security;

create policy "read sessions"  on public.sessions        for select using (true);
create policy "read participants" on public.participants for select using (true);
create policy "read groups"    on public.question_groups for select using (true);
create policy "read questions" on public.questions       for select using (true);

create policy "join active session" on public.participants for insert
  with check (exists (select 1 from public.sessions s
                      where s.id = session_id and s.status = 'active'));

create policy "ask in active session" on public.questions for insert
  with check (
    classification_status = 'pending'
    and group_id is null
    and classification_attempts = 0
    and exists (select 1 from public.sessions s
                where s.id = session_id and s.status = 'active')
    and exists (select 1 from public.participants p
                where p.id = participant_id and p.session_id = questions.session_id)
  );

-- Only expose the columns the browser needs to write.
revoke insert, update, delete on public.sessions from anon, authenticated;
revoke all on public.session_host_keys from anon, authenticated;
revoke update, delete on public.participants, public.questions, public.question_groups from anon, authenticated;
revoke insert on public.question_groups from anon, authenticated;

